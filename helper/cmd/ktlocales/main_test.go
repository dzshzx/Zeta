const sample = `{
  "@@locale": "zh-Hans",
  "plain": "已停止",
  "@plain": { "description": "灰色提示，可以有 */ 和 /* 这样的字" },
  "files": "{host} 上选了 {count, plural, other {# 个文件}}，{when, date, short}",
  "@files": {
    "description": "状态栏。",
    "placeholders": { "count": { "type": "num" }, "host": {} }
  },
  "keywords": "{in} {0} {catalog} {in_}"
}`

// 键按文件里的先后；占位先按声明的先后、再补消息里的，类型照声明或照 mygo 推断；参数名避开关键字和函数体里的名字。
func TestGeneratesTypedFunctions(t *testing.T) {
	keys, err := parse([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	got := string(kotlin(catalog{dir: "x/locales", name: "x", object: "XStrings", doc: "试的。"}, keys))
	for _, want := range []string{
		"// Code generated by helper/cmd/ktlocales from x/locales. DO NOT EDIT.\n",
		"object XStrings {\n",
		`    val catalog = Catalog("x")` + "\n",
		"     * 「已停止」\n     *\n     * 灰色提示，可以有 * / 和 / * 这样的字\n",
		`    fun plain(): String = catalog.say("plain")` + "\n",
		`    fun files(count: Number, host: String, when_: java.util.Date): String =` +
			` catalog.say("files", mapOf("count" to count, "host" to host, "when" to when_))` + "\n",
		`    fun keywords(in_: String, arg0: String, catalog_: String, in__: String): String =` +
			` catalog.say("keywords", mapOf("in" to in_, "0" to arg0, "catalog" to catalog_, "in_" to in__))` + "\n",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("生成的代码里没有\n%s\n全文：\n%s", want, got)
		}
	}
	if strings.Index(got, "fun plain(") > strings.Index(got, "fun files(") {
		t.Error("没按文件里的先后")
	}
}

// 没声明类型的复数参数是 Int，和 mygo 一样。
func TestInfersPluralAsInt(t *testing.T) {
	keys, err := parse([]byte(`{"n": "{count, plural, one {# file} other {# files}}"}`))
	if err != nil {
		t.Fatal(err)
	}
	if got := kotlin(catalog{object: "X"}, keys); !strings.Contains(string(got), "fun n(count: Int)") {
		t.Errorf("%s", got)
	}
}

func TestRejectsBrokenCatalogs(t *testing.T) {
	for name, data := range map[string]string{
		"消息解析不了": `{"a": "{count, plural, one {x}"}`,
		"类型不认识":  `{"a": "{n}", "@a": {"placeholders": {"n": {"type": "Long"}}}}`,
		"键重复":    `{"a": "x", "a": "y"}`,
		"不是对象":   `["a"]`,
		"值不是字符串": `{"a": 1}`,
	} {
		if _, err := parse([]byte(data)); err == nil {
			t.Errorf("%s：没报错", name)
		}
	}
}

// 生成的文件只在内容变了时才写：门禁重新生成后靠「已跟踪文件不变」核对，没变时不动修改时间。
func TestWritesOnlyChanges(t *testing.T) {
	root := t.TempDir()
	c := catalog{dir: "locales", name: "x", object: "XStrings"}
	if err := os.MkdirAll(filepath.Join(root, c.dir), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, c.dir, "zh-Hans.json"), []byte(sample), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := write(root, c); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(root, outDir, "XStrings.gen.kt")
	before, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chtimes(out, before.ModTime().Add(-3600e9), before.ModTime().Add(-3600e9)); err != nil {
		t.Fatal(err)
	}
	if err := write(root, c); err != nil {
		t.Fatal(err)
	}
	after, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if !after.ModTime().Before(before.ModTime()) {
		t.Error("内容没变也重写了")
	}
}
