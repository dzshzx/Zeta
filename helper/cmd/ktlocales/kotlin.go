package main

import (
	"bytes"
	"fmt"
	"slices"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"
)

// kotlinKeywords 是 Kotlin 的硬关键字：参数名撞上时后面加 _，函数名撞上时用反引号。
var kotlinKeywords = strings.Fields(`as break class continue do else false for fun if in interface is null object
package return super this throw true try typealias typeof val var when while`)

// reservedParams 是生成的函数体里用到的名字，参数不能盖住它们。
var reservedParams = []string{"catalog", "mapOf", "to"}

// kotlin 写出 c 的取字对象：每个键一个函数，按界面语言出字（Catalog.say）。
func kotlin(c catalog, keys []key) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by helper/cmd/ktlocales from %s. DO NOT EDIT.\n\n", c.dir)
	b.WriteString("package com.dzshzx.zeta.i18n\n\n")
	fmt.Fprintf(&b, "/** %s各函数按界面语言（[UiLanguage.current]）出字，那种语言缺的句子用简体中文。 */\n", comment(c.doc))
	fmt.Fprintf(&b, "object %s {\n", c.object)
	fmt.Fprintf(&b, "    /** 这份文字表本身：按种类码出字（[Catalog.sayOrNull]）时用。 */\n")
	fmt.Fprintf(&b, "    val catalog = Catalog(%s)\n", strconv.Quote(c.name))
	for _, k := range keys {
		b.WriteString("\n")
		writeFunc(&b, k)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func writeFunc(b *bytes.Buffer, k key) {
	b.WriteString("    /**\n")
	fmt.Fprintf(b, "     * 「%s」\n", comment(k.message))
	if k.description != "" {
		b.WriteString("     *\n")
		fmt.Fprintf(b, "     * %s\n", comment(k.description))
	}
	b.WriteString("     */\n")
	used := map[string]bool{}
	var params, args []string
	for _, p := range k.params {
		name := paramName(p.name, used)
		params = append(params, name+": "+arbTypes[p.typ])
		args = append(args, strconv.Quote(p.name)+" to "+name)
	}
	call := "catalog.say(" + strconv.Quote(k.name)
	if len(args) > 0 {
		call += ", mapOf(" + strings.Join(args, ", ") + ")"
	}
	fmt.Fprintf(b, "    fun %s(%s): String = %s)\n", funcName(k.name), strings.Join(params, ", "), call)
}

// comment 是放进 KDoc 的一行：换行压成空格，拆开 */ 和 /*（Kotlin 的注释能嵌套，/* 也会打开一层）。
func comment(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	s = strings.ReplaceAll(s, "*/", "* /")
	return strings.ReplaceAll(s, "/*", "/ *")
}

// funcName 是键的函数名：键本身（文字表的键是小驼峰的英文名），撞上关键字时加反引号。
func funcName(key string) string {
	if slices.Contains(kotlinKeywords, key) {
		return "`" + key + "`"
	}
	return key
}

// paramName 是占位 name 在函数里的参数名：数字开头的前面加 arg，撞上关键字或函数体里的名字的后面加 _，和别的参数不重名。
func paramName(name string, used map[string]bool) string {
	if r, _ := utf8.DecodeRuneInString(name); unicode.IsDigit(r) {
		name = "arg" + name
	}
	if slices.Contains(kotlinKeywords, name) || slices.Contains(reservedParams, name) {
		name += "_"
	}
	for used[name] {
		name += "_"
	}
	used[name] = true
	return name
}
