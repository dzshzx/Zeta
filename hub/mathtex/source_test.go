package mathtex

import "testing"

// 哪些算公式照手机版（TexMathDelimiters、ChatMathSequentialParser）；标「mygo 不同」的是 mygo 自己的判定会弄错的。
func TestMathSource(t *testing.T) {
	for _, c := range []struct{ name, in, want string }{
		{"行内公式", `勾股定理 $x^2+y^2=z^2$。`, `勾股定理 \(x^2+y^2=z^2\)。`},
		{"紧贴中文", `面积$S$等于$\pi r^2$`, `面积\(S\)等于\(\pi r^2\)`},
		{"括号里", `（$a$）和($b$)`, `（\(a\)）和(\(b\))`},
		{"开头紧跟数字（mygo 不同）", `$2x$ 和 $3.14$`, `\(2x\) 和 \(3.14\)`},
		{"金额", `$4 和 $20`, `$4 和 $20`},
		{"金额区间", `$4-$20`, `$4-$20`},
		{"金额后的公式（mygo 不同）", `$a $b$`, `$a \(b\)`},
		{"金额后的公式", `$5 买了 $x$ 个`, `$5 买了 \(x\) 个`},
		{"前面是字母", `a$x$`, `a$x$`},
		{"后面是字母", `$x$y`, `$x$y`},
		{"开头后是空格", `$ x$`, `$ x$`},
		{"结尾前是空格", `$x $`, `$x $`},
		{"空的", `$ $`, `$ $`},
		{"转义的美元", `\$5 和 $x$`, `\$5 和 \(x\)`},
		{"跨行", "$a\nb$", "\\(a\nb\\)"},
		{"不跨空行", "$a\n\nb$", "$a\n\nb$"},
		{"不跨列表项", "- $a\n- b$", "- $a\n- b$"},
		{"不跨表格的格", "| $a | b$ |", "| $a | b$ |"},
		{"行内代码", "`$x$` 和 $y$", "`$x$` 和 \\(y\\)"},
		{"代码围栏", "```\n$x$\n```\n$y$", "```\n$x$\n```\n\\(y\\)"},
		{"链接", `[看 $x$](https://x.y/$a$) 和 $b$`, `[看 $x$](https://x.y/$a$) 和 \(b\)`},
		{"$$ 不动", `$$x$$ 和 $y$`, `$$x$$ 和 \(y\)`},
		{"$$ 里的 $ 不动", `$$a $b$ c$$`, `$$a $b$ c$$`},
		{"\\( 不动", `\(x\) 和 $y$`, `\(x\) 和 \(y\)`},
		{"\\( 里的 $ 不动", `\(a $b$ c\)`, `\(a $b$ c\)`},
		{"转义的方括号（mygo 不同）", `arr\[0\] = 1`, `arr&#91;0\] = 1`},
		{"行首的块公式", "\\[\nx^2\n\\]", "\\[\nx^2\n\\]"},
		{"行首单行的块公式", `\[x^2\]`, `\[x^2\]`},
		{"块公式后面有字（mygo 不同）", `\[x\] 是区间`, `&#91;x\] 是区间`},
		{"公式里的 \\[ 不换", `$a\[b$`, `\(a\[b\)`},
		{"没有公式", `普通的一句话`, `普通的一句话`},
	} {
		if got := Source(c.in); got != c.want {
			t.Errorf("%s: Source(%q) = %q, want %q", c.name, c.in, got, c.want)
		}
	}
}
